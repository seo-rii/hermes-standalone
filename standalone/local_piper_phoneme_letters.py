def is_letter(tr,letter,group):
    if not 0<=group<8:return 0
    members=tr.letter_groups[group]
    if members is not None:return int(letter in members)
    if tr.letter_bits_offset>0:
        shifted=letter-tr.letter_bits_offset
        if not 0<shifted<0x100:return 0
        letter=shifted
    elif 0xc0<=letter<0x25e:
        return tr.letter_bits[REMOVE_ACCENT[letter-0xc0]]&(1<<group)
    return tr.letter_bits[letter]&(1<<group) if 0<=letter<0x100 else 0


BRACKETS=(40,41,91,93,123,125,60,62,34,39,96,0xab,0xbb,0x300a,0x300b,0xe03c)


def is_bracket(code):
    if 0x2014<=code<=0x201f:return 1
    try:return BRACKETS.index(code)+1
    except ValueError:return 0
