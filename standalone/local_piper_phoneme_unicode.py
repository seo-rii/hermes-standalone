def utf8_out(code):
    code=_point(code)
    if code<0x80:return bytes((code,))
    if code>=0x110000:return b' '
    count=1 if code<0x800 else 2 if code<0x10000 else 3
    shift=count*6
    output=bytearray(((0,0xc0,0xe0,0xf0)[count]|code>>shift,))
    for _ in range(count):
        shift-=6;output.append(0x80+(code>>shift&0x3f))
    return bytes(output)


def utf8_in(buffer,cursor=0,backwards=False):
    def byte(index):
        return buffer[index] if 0<=index<len(buffer) else 0
    while byte(cursor)&0xc0==0x80:
        cursor+=-1 if backwards else 1
    first=byte(cursor);cursor+=1;count=0
    if first&0x80:
        count=1 if first&0xe0==0xc0 else 2 if first&0xf0==0xe0 else 3 if first&0xf8==0xf0 else 0
        first&=(0xff,0x1f,0x0f,0x07)[count]
        consumed=0
        for _ in range(count):
            next_byte=byte(cursor)
            if next_byte==0:break
            first=(first<<6)+(next_byte&0x3f);cursor+=1;consumed+=1
        count=consumed
